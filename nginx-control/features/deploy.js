'use strict';
/**
 * Deployment pipeline and backups.
 *
 * Pull -> test in a throwaway container -> back up -> copy -> reload. The test
 * is the point of the whole thing, and it earned its complexity the hard way:
 *
 *  - Bind-mount sources must be HOST paths. Handing the daemon a path that only
 *    exists inside this container makes it create an empty directory and mount
 *    that, so the test validated nothing while reporting success.
 *  - The sandbox inherits the production container's mounts, minus the config
 *    directories it replaces. Hardcoding the list meant every mount an operator
 *    added later — GeoIP databases, webroot — broke `nginx -t`.
 *  - It runs on the production network. nginx resolves upstream hostnames while
 *    parsing, so an isolated container fails on every `upstream` naming a real
 *    host.
 *
 * Copying is recursive: config trees are not flat, and `ssl/<ca>/` was being
 * silently dropped. Deletions skip dotfiles and are abandoned entirely when the
 * source directory is empty — a repo folder holding only a `.gitkeep` would
 * otherwise wipe the live configuration.
 *
 * Without a Git repository the copy is additive only: the work tree then holds
 * a subset of the configuration, so removing what is missing from it would
 * delete files that were never managed here.
 */

